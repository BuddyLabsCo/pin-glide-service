// Command pin-glide-api runs the Pin Glide HTTP and WebSocket service. Its
// -openapi and -asyncapi modes export one published protocol description on
// stdout and exit instead of starting the service.
package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"log/slog"
	"net"
	"os"
	"os/signal"
	"syscall"

	"github.com/BuddyLabsCo/pin-glide-service/internal/api"
	"github.com/BuddyLabsCo/pin-glide-service/internal/api/httpapi"
	"github.com/BuddyLabsCo/pin-glide-service/internal/api/wss"
	"github.com/BuddyLabsCo/pin-glide-service/internal/config"
	"github.com/BuddyLabsCo/pin-glide-service/internal/db"
	"github.com/BuddyLabsCo/pin-glide-service/internal/observability"
)

func main() {
	exportOpenAPI := flag.Bool("openapi", false, "write the published HTTP description as YAML to stdout and exit")
	exportAsyncAPI := flag.Bool("asyncapi", false, "write the published WSS description as YAML to stdout and exit")
	flag.Parse()

	if err := run(*exportOpenAPI, *exportAsyncAPI); err != nil {
		fmt.Fprintf(os.Stderr, "pin-glide-api: %v\n", err)
		os.Exit(1)
	}
}

// run serves the composed API, or exports one published description and
// returns. The export modes read no configuration, open no listener and
// contact no database or provider, so the contracts can be regenerated by any
// checkout and by release automation without live service dependencies.
func run(exportOpenAPI, exportAsyncAPI bool) error {
	switch {
	case exportOpenAPI && exportAsyncAPI:
		return errors.New("choose at most one of -openapi and -asyncapi")
	case exportOpenAPI:
		return httpapi.WriteOpenAPI(os.Stdout)
	case exportAsyncAPI:
		return wss.WriteAsyncAPI(os.Stdout)
	}

	configuration, err := config.Load(os.Getenv)
	if err != nil {
		return err
	}

	ctx, stop := signal.NotifyContext(context.Background(), syscall.SIGINT, syscall.SIGTERM)
	defer stop()

	pool, err := db.Open(ctx, configuration.DatabaseURL)
	if err != nil {
		return err
	}
	defer func() { _ = pool.Close() }()

	listener, err := net.Listen("tcp", configuration.APIAddress)
	if err != nil {
		return fmt.Errorf("listen on %s: %w", configuration.APIAddress, err)
	}

	logger := observability.NewLogger(os.Stderr, string(configuration.Environment))
	logger.Info("api listening", slog.String("address", listener.Addr().String()))

	return api.Serve(ctx, listener, api.Dependencies{Database: pool, Logger: logger})
}
